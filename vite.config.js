import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

import { defineConfig } from 'vite';

/*
  One build target. There is no build-mode switch here and there must not become one: this is a
  static site, `vite build` is the whole of it, and nothing in it may need a server.

  `publicDir` stays at its default `public/`, which is where the nine environment maps, the Filmic
  LUTs and the twelve material dumps live.
*/

/*
  `THIRD-PARTY-NOTICES.txt`: the licence file of every package that rendered code into the bundle.
  The minifier strips licence headers, and credits for code a package adapted from others are
  curated by hand in `docs/attributions.md`. The worker is a separate build that runs none of
  `plugins`, so it gets the collector too.
*/
function thirdPartyNotices() {
  const packages = new Map();
  const collect = (bundle) => {
    for (const chunk of Object.values(bundle)) {
      if (chunk.type !== 'chunk') continue;
      for (const [id, module] of Object.entries(chunk.modules)) {
        const at = id.lastIndexOf('/node_modules/');
        if (!module.renderedLength || at < 0 || id.startsWith('\0')) continue;
        const parts = id.slice(at + '/node_modules/'.length).split('/');
        const name = parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0];
        packages.set(name, `${id.slice(0, at)}/node_modules/${name}`);
      }
    }
  };
  const worker = { name: 'foldray:third-party-notices-worker', apply: 'build', generateBundle(_, bundle) { collect(bundle); } };
  const main = {
    name: 'foldray:third-party-notices',
    apply: 'build',
    generateBundle(_, bundle) {
      collect(bundle);
      const rule = '='.repeat(100);
      let text = 'THIRD-PARTY NOTICES\n\nGenerated by the build from the packages whose code this bundle contains.'
        + '\nThe Licence & Attributions page, https://www.foldray.org/home/#licence, is the readable account of these and of everything else.\n';
      for (const name of [...packages.keys()].sort()) {
        const dir = packages.get(name);
        const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
        const licence = readdirSync(dir).find((file) => /^(?:licen[cs]e|copying)(?:\.|$)/i.test(file));
        text += `\n${rule}\n${meta.name} ${meta.version} -- ${meta.license}\n${rule}\n\n`;
        text += licence ? readFileSync(join(dir, licence), 'utf8').trim() : `No licence file; package.json declares ${meta.license}.`;
        text += '\n';
      }
      this.emitFile({ type: 'asset', fileName: 'THIRD-PARTY-NOTICES.txt', source: text });
    },
  };
  return { main, worker };
}

/*
  The shaders are imported `?raw`, so their comments -- notes for this tree -- would ship as string
  literals the minifier cannot touch. WGSL block comments nest and WGSL has no string literals.
  Newlines are kept so a compile error still names the source line.
*/
export function stripWgslComments(source) {
  let out = '';
  let depth = 0;
  for (let i = 0; i < source.length; i += 1) {
    const two = source.slice(i, i + 2);
    if (two === '/*') { depth += 1; i += 1; continue; }
    if (depth > 0) {
      if (two === '*/') { depth -= 1; i += 1; } else if (source[i] === '\n') out += '\n';
      continue;
    }
    if (two === '//') {
      while (i < source.length && source[i] !== '\n') i += 1;
      if (i < source.length) out += '\n';
      continue;
    }
    out += source[i];
  }
  return out;
}

function strippedShaders() {
  return {
    name: 'foldray:stripped-shaders',
    apply: 'build',
    enforce: 'pre',
    load(id) {
      if (!id.endsWith('.wgsl?raw')) return null;
      return `export default ${JSON.stringify(stripWgslComments(readFileSync(id.slice(0, -'?raw'.length), 'utf8')))};`;
    },
  };
}

// `index.html`'s comments are notes for this tree, not part of the page.
function stripHtmlComments() {
  return {
    name: 'foldray:strip-html-comments',
    apply: 'build',
    transformIndexHtml: { order: 'post', handler: (html) => html.replace(/\n?[ \t]*<!--[\s\S]*?-->/g, '') },
  };
}

const notices = thirdPartyNotices();

export default defineConfig({
  plugins: [notices.main, strippedShaders(), stripHtmlComments()],
  build: {
    // The renderer's Worker is a real module Worker (`render/scene-build-worker.js`), so the
    // build must emit ES-module workers rather than the classic IIFE default.
    target: 'es2022',
    /*
      Vite's own chunks go to `dist/bundle/`, not to its default `dist/assets/`.

      `public/assets/` is the renderer's runtime asset root -- `asset-base.js` resolves `/assets` --
      and Vite copies `public/` to the root of `dist/`, so the default would merge the build's
      hashed chunks into the same directory as the environment maps, the LUTs and the material
      dumps. Nothing collides today; a future emitted `luts.json` or `env/` would, and it would
      collide silently by overwriting a file the tracer fetches.
    */
    assetsDir: 'bundle',
    // Every browser with WebGPU supports `modulepreload`, so Vite's polyfill would be dead code.
    modulePreload: { polyfill: false },
  },
  worker: {
    format: 'es',
    // The worker build runs none of `plugins`, so the notices collector is handed to it.
    plugins: () => [notices.worker],
  },
});
